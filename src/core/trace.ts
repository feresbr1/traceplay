/**
 * The traceplay recorder. A trace function receives `t` and builds tracked structures
 * (arrays, grids, graphs, trees, variables). Every change or highlight records a frame:
 * a full snapshot of every structure, so the player can jump to any step.
 */

export type Tone =
  | 'active'
  | 'compare'
  | 'swap'
  | 'done'
  | 'visited'
  | 'frontier'
  | 'path'
  | 'found'
  | 'muted'
  | 'error'
  | 'pivot';

export const TONES: Tone[] = [
  'active',
  'compare',
  'swap',
  'done',
  'visited',
  'frontier',
  'path',
  'found',
  'muted',
  'error',
  'pivot',
];

export type Value = number | string | boolean | null;

export interface ArrayItem {
  /** Stable identity, so the player can animate an item moving between indexes. */
  key: string;
  value: Value;
}

export interface ArrayState {
  kind: 'array';
  name: string;
  style: 'bars' | 'cells';
  items: ArrayItem[];
  marks: Record<number, Tone>;
  pointers: { name: string; index: number }[];
}

export interface GridState {
  kind: 'grid';
  name: string;
  cells: Value[][];
  marks: Record<string, Tone>;
  pointers: { name: string; row: number; col: number }[];
}

export interface GraphNode {
  id: string;
  label: string;
  x?: number;
  y?: number;
}

export interface GraphEdge {
  from: string;
  to: string;
  weight?: Value;
}

export interface GraphState {
  kind: 'graph';
  name: string;
  directed: boolean;
  layout: 'circle' | 'force' | 'manual' | 'layered';
  nodes: GraphNode[];
  edges: GraphEdge[];
  nodeMarks: Record<string, Tone>;
  edgeMarks: Record<string, Tone>;
  nodeBadges: Record<string, Value>;
}

export interface TreeNode {
  id: string;
  value: Value;
  /** For binary trees children are [left, right]; null keeps the slot. */
  children: (string | null)[];
}

export interface TreeState {
  kind: 'tree';
  name: string;
  binary: boolean;
  root: string | null;
  nodes: Record<string, TreeNode>;
  marks: Record<string, Tone>;
}

export interface VarsState {
  kind: 'vars';
  name: string;
  values: Record<string, Value>;
  changed: string[];
}

export type StructState = ArrayState | GridState | GraphState | TreeState | VarsState;

export interface Frame {
  structs: StructState[];
  /** Narration set with t.say(); persists until changed. */
  caption: string;
  /** What just happened, generated by the API ("swap arr[0] and arr[3]"). */
  event: string;
  /** 1-based line in meta.code, set with t.line(). */
  line?: number;
}

export interface TraceMeta {
  title?: string;
  description?: string;
  code?: string;
  language?: string;
}

export interface Trace {
  version: 1;
  meta: TraceMeta;
  frames: Frame[];
}

export const MAX_FRAMES = 5000;

export class TraceError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'TraceError';
  }
}

const clone = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;

interface Tracked {
  state: StructState;
  /** Highlights that only last one frame. */
  transient: () => void;
}

export class Tracer {
  private readonly structs: Tracked[] = [];
  private readonly frames: Frame[] = [];
  private caption = '';
  private currentLine: number | undefined;
  private paused = 0;

  /** Narration shown under the animation until the next say(). */
  say(text: string): void {
    this.caption = String(text);
  }

  /** Highlight a line of meta.code (1-based) from the next frame on. */
  line(n: number): void {
    this.currentLine = n;
  }

  /** Record a frame explicitly, optionally with a new caption. */
  step(caption?: string): void {
    if (caption !== undefined) this.caption = String(caption);
    this.record('');
  }

  /** Run several changes as one frame. */
  batch(fn: () => void, event = ''): void {
    this.paused++;
    try {
      fn();
    } finally {
      this.paused--;
    }
    this.record(event);
  }

  array(name: string, values: Value[], options: { style?: 'bars' | 'cells' } = {}): TrackedArray {
    const numeric = values.every((v) => typeof v === 'number');
    const state: ArrayState = {
      kind: 'array',
      name,
      style: options.style ?? (numeric && values.length > 1 ? 'bars' : 'cells'),
      items: values.map((value, i) => ({ key: `${name}#${i}`, value })),
      marks: {},
      pointers: [],
    };
    const arr = new TrackedArray(this, state);
    this.register(state, () => arr.clearTransient());
    this.record(`create ${name}`);
    return arr;
  }

  grid(name: string, cells: Value[][]): TrackedGrid {
    const state: GridState = { kind: 'grid', name, cells: clone(cells), marks: {}, pointers: [] };
    const grid = new TrackedGrid(this, state);
    this.register(state, () => grid.clearTransient());
    this.record(`create ${name}`);
    return grid;
  }

  graph(
    name: string,
    spec: {
      nodes: (string | { id: string; label?: string; x?: number; y?: number })[];
      edges?: (
        [string, string] | [string, string, Value] | { from: string; to: string; weight?: Value }
      )[];
      directed?: boolean;
      layout?: GraphState['layout'];
    },
  ): TrackedGraph {
    const nodes = spec.nodes.map((n) =>
      typeof n === 'string'
        ? { id: n, label: n }
        : { id: n.id, label: n.label ?? n.id, x: n.x, y: n.y },
    );
    const ids = new Set(nodes.map((n) => n.id));
    const edges = (spec.edges ?? []).map((e) => {
      const edge = Array.isArray(e) ? { from: e[0], to: e[1], weight: e[2] } : e;
      if (!ids.has(edge.from) || !ids.has(edge.to)) {
        throw new TraceError(
          `Edge ${edge.from} → ${edge.to} refers to a node that is not in ${name}.`,
        );
      }
      return edge.weight === undefined ? { from: edge.from, to: edge.to } : edge;
    });
    const manual = nodes.every((n) => typeof n.x === 'number' && typeof n.y === 'number');
    const state: GraphState = {
      kind: 'graph',
      name,
      directed: spec.directed ?? false,
      layout: spec.layout ?? (manual ? 'manual' : nodes.length <= 10 ? 'circle' : 'force'),
      nodes,
      edges,
      nodeMarks: {},
      edgeMarks: {},
      nodeBadges: {},
    };
    const graph = new TrackedGraph(this, state);
    this.register(state, () => graph.clearTransient());
    this.record(`create ${name}`);
    return graph;
  }

  tree(name: string, options: { binary?: boolean } = {}): TrackedTree {
    const state: TreeState = {
      kind: 'tree',
      name,
      binary: options.binary ?? true,
      root: null,
      nodes: {},
      marks: {},
    };
    const tree = new TrackedTree(this, state);
    this.register(state, () => tree.clearTransient());
    this.record(`create ${name}`);
    return tree;
  }

  vars(name: string, values: Record<string, Value> = {}): TrackedVars {
    const state: VarsState = { kind: 'vars', name, values: { ...values }, changed: [] };
    const vars = new TrackedVars(this, state);
    this.register(state, () => {
      state.changed = [];
    });
    this.record(`create ${name}`);
    return vars;
  }

  /** @internal */
  record(event: string): void {
    if (this.paused > 0) return;
    if (this.frames.length >= MAX_FRAMES) {
      throw new TraceError(
        `More than ${MAX_FRAMES} frames. Trace a smaller input, or group changes with t.batch().`,
      );
    }
    this.frames.push({
      structs: this.structs.map((s) => clone(s.state)),
      caption: this.caption,
      event,
      ...(this.currentLine !== undefined ? { line: this.currentLine } : {}),
    });
    for (const s of this.structs) s.transient();
  }

  private register(state: StructState, transient: () => void): void {
    if (this.structs.some((s) => s.state.name === state.name)) {
      throw new TraceError(`A structure named "${state.name}" already exists.`);
    }
    this.structs.push({ state, transient });
  }

  /** @internal */
  result(meta: TraceMeta): Trace {
    // A closing t.say() with no change after it would otherwise never be shown.
    const last = this.frames[this.frames.length - 1];
    if (last && (last.caption !== this.caption || last.line !== this.currentLine)) this.record('');
    return { version: 1, meta: { ...meta }, frames: this.frames };
  }
}

function checkTone(tone: string): Tone {
  if (!(TONES as string[]).includes(tone)) {
    throw new TraceError(`Unknown tone "${tone}". Use one of: ${TONES.join(', ')}.`);
  }
  return tone as Tone;
}

function fmt(v: Value): string {
  return typeof v === 'string' ? JSON.stringify(v) : String(v);
}

export class TrackedArray {
  private transient: number[] = [];
  private nextKey: number;

  constructor(
    private readonly t: Tracer,
    private readonly state: ArrayState,
  ) {
    this.nextKey = state.items.length;
  }

  get length(): number {
    return this.state.items.length;
  }

  /** Current values (a copy). */
  values(): Value[] {
    return this.state.items.map((i) => i.value);
  }

  get(i: number): Value {
    return this.item(i).value;
  }

  set(i: number, value: Value): void {
    this.item(i).value = value;
    this.flash(i, 'active');
    this.t.record(`${this.state.name}[${i}] = ${fmt(value)}`);
  }

  swap(i: number, j: number): void {
    const a = this.item(i);
    const b = this.item(j);
    this.state.items[i] = b;
    this.state.items[j] = a;
    this.flash(i, 'swap');
    this.flash(j, 'swap');
    this.t.record(`swap ${this.state.name}[${i}] and ${this.state.name}[${j}]`);
  }

  compare(i: number, j: number): void {
    this.item(i);
    this.item(j);
    this.flash(i, 'compare');
    this.flash(j, 'compare');
    this.t.record(`compare ${this.state.name}[${i}] and ${this.state.name}[${j}]`);
  }

  /** Highlight one index for a single frame. */
  focus(i: number, tone: Tone = 'active'): void {
    this.item(i);
    this.flash(i, checkTone(tone));
    this.t.record(`look at ${this.state.name}[${i}]`);
  }

  /** Persistent mark (until unmark). */
  mark(i: number | number[], tone: Tone = 'active'): void {
    const list = Array.isArray(i) ? i : [i];
    for (const idx of list) {
      this.item(idx);
      this.state.marks[idx] = checkTone(tone);
    }
    this.t.record(`mark ${this.state.name}[${list.join(', ')}] ${tone}`);
  }

  unmark(i?: number | number[]): void {
    if (i === undefined) this.state.marks = {};
    else for (const idx of Array.isArray(i) ? i : [i]) delete this.state.marks[idx];
    this.t.record('');
  }

  /** Show a labelled pointer under an index; pass null to remove it. */
  pointer(name: string, index: number | null): void {
    this.state.pointers = this.state.pointers.filter((p) => p.name !== name);
    if (index !== null) {
      if (index < 0 || index > this.state.items.length) {
        throw new TraceError(
          `Pointer ${name}=${index} is outside ${this.state.name} (length ${this.length}).`,
        );
      }
      this.state.pointers.push({ name, index });
    }
    this.t.record(index === null ? '' : `${name} = ${index}`);
  }

  push(value: Value): void {
    this.state.items.push({ key: `${this.state.name}#${this.nextKey++}`, value });
    this.flash(this.state.items.length - 1, 'active');
    this.t.record(`push ${fmt(value)}`);
  }

  pop(): Value {
    const item = this.state.items.pop();
    if (!item) throw new TraceError(`pop() on empty ${this.state.name}.`);
    this.t.record(`pop ${fmt(item.value)}`);
    return item.value;
  }

  unshift(value: Value): void {
    this.state.items.unshift({ key: `${this.state.name}#${this.nextKey++}`, value });
    this.shiftMarks(1);
    this.flash(0, 'active');
    this.t.record(`unshift ${fmt(value)}`);
  }

  shift(): Value {
    const item = this.state.items.shift();
    if (!item) throw new TraceError(`shift() on empty ${this.state.name}.`);
    this.shiftMarks(-1);
    this.t.record(`shift ${fmt(item.value)}`);
    return item.value;
  }

  private shiftMarks(by: number): void {
    const next: Record<number, Tone> = {};
    for (const [k, v] of Object.entries(this.state.marks)) {
      const idx = Number(k) + by;
      if (idx >= 0) next[idx] = v;
    }
    this.state.marks = next;
  }

  private item(i: number): ArrayItem {
    const item = this.state.items[i];
    if (!item) {
      throw new TraceError(
        `Index ${i} is outside ${this.state.name} (length ${this.state.items.length}).`,
      );
    }
    return item;
  }

  private saved: Record<number, Tone> = {};

  private flash(i: number, tone: Tone): void {
    if (!(i in this.saved)) this.saved[i] = this.state.marks[i] as Tone;
    this.state.marks[i] = tone;
    this.transient.push(i);
  }

  /** @internal */
  clearTransient(): void {
    for (const i of this.transient) {
      const prev = this.saved[i];
      if (prev === undefined) delete this.state.marks[i];
      else this.state.marks[i] = prev;
    }
    this.transient = [];
    this.saved = {};
  }
}

export class TrackedGrid {
  private transient: string[] = [];
  private saved: Record<string, Tone | undefined> = {};

  constructor(
    private readonly t: Tracer,
    private readonly state: GridState,
  ) {}

  get rows(): number {
    return this.state.cells.length;
  }

  get cols(): number {
    return this.state.cells[0]?.length ?? 0;
  }

  get(r: number, c: number): Value {
    this.check(r, c);
    return this.state.cells[r]![c]!;
  }

  set(r: number, c: number, value: Value): void {
    this.check(r, c);
    this.state.cells[r]![c] = value;
    this.flash(r, c, 'active');
    this.t.record(`${this.state.name}[${r}][${c}] = ${fmt(value)}`);
  }

  mark(r: number, c: number, tone: Tone = 'active'): void {
    this.check(r, c);
    this.state.marks[`${r},${c}`] = checkTone(tone);
    this.t.record(`mark (${r}, ${c}) ${tone}`);
  }

  unmark(r?: number, c?: number): void {
    if (r === undefined || c === undefined) this.state.marks = {};
    else delete this.state.marks[`${r},${c}`];
    this.t.record('');
  }

  focus(r: number, c: number, tone: Tone = 'active'): void {
    this.check(r, c);
    this.flash(r, c, checkTone(tone));
    this.t.record(`look at (${r}, ${c})`);
  }

  pointer(name: string, r: number | null, c?: number): void {
    this.state.pointers = this.state.pointers.filter((p) => p.name !== name);
    if (r !== null && c !== undefined) {
      this.check(r, c);
      this.state.pointers.push({ name, row: r, col: c });
    }
    this.t.record(r === null ? '' : `${name} at (${r}, ${c})`);
  }

  private check(r: number, c: number): void {
    if (r < 0 || r >= this.rows || c < 0 || c >= this.cols) {
      throw new TraceError(
        `Cell (${r}, ${c}) is outside ${this.state.name} (${this.rows}×${this.cols}).`,
      );
    }
  }

  private flash(r: number, c: number, tone: Tone): void {
    const k = `${r},${c}`;
    if (!(k in this.saved)) this.saved[k] = this.state.marks[k];
    this.state.marks[k] = tone;
    this.transient.push(k);
  }

  /** @internal */
  clearTransient(): void {
    for (const k of this.transient) {
      const prev = this.saved[k];
      if (prev === undefined) delete this.state.marks[k];
      else this.state.marks[k] = prev;
    }
    this.transient = [];
    this.saved = {};
  }
}

const edgeKey = (from: string, to: string) => `${from}->${to}`;

export class TrackedGraph {
  private transient: { kind: 'node' | 'edge'; key: string; prev?: Tone }[] = [];

  constructor(
    private readonly t: Tracer,
    private readonly state: GraphState,
  ) {}

  neighbors(id: string): string[] {
    this.node(id);
    const out: string[] = [];
    for (const e of this.state.edges) {
      if (e.from === id) out.push(e.to);
      else if (!this.state.directed && e.to === id) out.push(e.from);
    }
    return out;
  }

  weight(from: string, to: string): Value | undefined {
    return this.edge(from, to).weight;
  }

  mark(id: string, tone: Tone = 'active'): void {
    this.node(id);
    this.state.nodeMarks[id] = checkTone(tone);
    this.t.record(`${id}: ${tone}`);
  }

  unmark(id?: string): void {
    if (id === undefined) this.state.nodeMarks = {};
    else delete this.state.nodeMarks[id];
    this.t.record('');
  }

  focus(id: string, tone: Tone = 'active'): void {
    this.node(id);
    this.transient.push({ kind: 'node', key: id, prev: this.state.nodeMarks[id] });
    this.state.nodeMarks[id] = checkTone(tone);
    this.t.record(`look at ${id}`);
  }

  markEdge(from: string, to: string, tone: Tone = 'active'): void {
    const e = this.edge(from, to);
    this.state.edgeMarks[edgeKey(e.from, e.to)] = checkTone(tone);
    this.t.record(`edge ${from}–${to}: ${tone}`);
  }

  focusEdge(from: string, to: string, tone: Tone = 'active'): void {
    const e = this.edge(from, to);
    const key = edgeKey(e.from, e.to);
    this.transient.push({ kind: 'edge', key, prev: this.state.edgeMarks[key] });
    this.state.edgeMarks[key] = checkTone(tone);
    this.t.record(`follow ${from} → ${to}`);
  }

  /** A small label next to a node, e.g. a distance. Pass null to clear. */
  badge(id: string, value: Value): void {
    this.node(id);
    if (value === null) delete this.state.nodeBadges[id];
    else this.state.nodeBadges[id] = value;
    this.t.record(value === null ? '' : `${id} = ${fmt(value)}`);
  }

  private node(id: string): GraphNode {
    const n = this.state.nodes.find((x) => x.id === id);
    if (!n) throw new TraceError(`No node "${id}" in ${this.state.name}.`);
    return n;
  }

  private edge(from: string, to: string): GraphEdge {
    const e = this.state.edges.find(
      (x) =>
        (x.from === from && x.to === to) ||
        (!this.state.directed && x.from === to && x.to === from),
    );
    if (!e) throw new TraceError(`No edge ${from} → ${to} in ${this.state.name}.`);
    return e;
  }

  /** @internal */
  clearTransient(): void {
    for (const item of this.transient.reverse()) {
      const marks = item.kind === 'node' ? this.state.nodeMarks : this.state.edgeMarks;
      if (item.prev === undefined) delete marks[item.key];
      else marks[item.key] = item.prev;
    }
    this.transient = [];
  }
}

export class TrackedTree {
  private counter = 0;
  private transient: { id: string; prev?: Tone }[] = [];

  constructor(
    private readonly t: Tracer,
    private readonly state: TreeState,
  ) {}

  get root(): string | null {
    return this.state.root;
  }

  value(id: string): Value {
    return this.node(id).value;
  }

  /** Child ids: [left, right] for binary trees (null when empty). */
  children(id: string): (string | null)[] {
    return [...this.node(id).children];
  }

  left(id: string): string | null {
    return this.node(id).children[0] ?? null;
  }

  right(id: string): string | null {
    return this.node(id).children[1] ?? null;
  }

  parent(id: string): string | null {
    for (const n of Object.values(this.state.nodes)) if (n.children.includes(id)) return n.id;
    return null;
  }

  /** Create the root (replacing any existing tree). Returns its id. */
  setRoot(value: Value): string {
    const id = this.newId();
    this.state.nodes = { [id]: { id, value, children: this.state.binary ? [null, null] : [] } };
    this.state.root = id;
    this.t.record(`root ${fmt(value)}`);
    return id;
  }

  /**
   * Add a child. Binary trees take side 'left' | 'right'; general trees append.
   * Returns the new node's id.
   */
  add(parentId: string, value: Value, side?: 'left' | 'right'): string {
    const parent = this.node(parentId);
    // Validate before creating anything, so a failed add leaves the tree unchanged.
    const slot = !this.state.binary ? -1 : side === 'right' ? 1 : side === 'left' ? 0 : -2;
    if (slot === -2)
      throw new TraceError('Binary trees need a side: add(parent, value, "left" | "right").');
    if (slot >= 0 && parent.children[slot]) {
      throw new TraceError(`Node ${fmt(parent.value)} already has a ${side} child.`);
    }
    const id = this.newId();
    this.state.nodes[id] = { id, value, children: this.state.binary ? [null, null] : [] };
    if (slot >= 0) parent.children[slot] = id;
    else parent.children.push(id);
    this.transient.push({ id, prev: this.state.marks[id] });
    this.state.marks[id] = 'active';
    this.t.record(`add ${fmt(value)} under ${fmt(parent.value)}`);
    return id;
  }

  setValue(id: string, value: Value): void {
    this.node(id).value = value;
    this.transient.push({ id, prev: this.state.marks[id] });
    this.state.marks[id] = 'active';
    this.t.record(`set ${fmt(value)}`);
  }

  /** Remove a node and its subtree. */
  remove(id: string): void {
    const parentId = this.parent(id);
    const drop = (nid: string) => {
      const n = this.state.nodes[nid];
      if (!n) return;
      for (const c of n.children) if (c) drop(c);
      delete this.state.nodes[nid];
      delete this.state.marks[nid];
    };
    if (parentId) {
      const p = this.node(parentId);
      p.children = p.children.map((c) => (c === id ? null : c));
      if (!this.state.binary) p.children = p.children.filter((c) => c !== null);
    } else if (this.state.root === id) {
      this.state.root = null;
    }
    drop(id);
    this.t.record('remove');
  }

  /**
   * Move a node (with its subtree) under a new parent, or make it the root (parentId null).
   * Rotations are a few attach() calls inside t.batch().
   */
  attach(id: string, parentId: string | null, side?: 'left' | 'right'): void {
    this.node(id);
    const old = this.parent(id);
    if (old) {
      const p = this.node(old);
      p.children = p.children.map((c) => (c === id ? null : c));
      if (!this.state.binary) p.children = p.children.filter((c) => c !== null);
    }
    if (parentId === null) {
      this.state.root = id;
    } else {
      const p = this.node(parentId);
      if (this.state.binary) {
        const slot = side === 'right' ? 1 : 0;
        p.children[slot] = id;
      } else {
        p.children.push(id);
      }
    }
    this.t.record('move subtree');
  }

  /** Detach a child slot without deleting the subtree (used inside rotations). */
  detach(parentId: string, side: 'left' | 'right'): string | null {
    const p = this.node(parentId);
    const slot = side === 'right' ? 1 : 0;
    const child = p.children[slot] ?? null;
    p.children[slot] = null;
    this.t.record('');
    return child;
  }

  mark(id: string, tone: Tone = 'active'): void {
    this.node(id);
    this.state.marks[id] = checkTone(tone);
    this.t.record(`${fmt(this.node(id).value)}: ${tone}`);
  }

  unmark(id?: string): void {
    if (id === undefined) this.state.marks = {};
    else delete this.state.marks[id];
    this.t.record('');
  }

  focus(id: string, tone: Tone = 'active'): void {
    this.node(id);
    this.transient.push({ id, prev: this.state.marks[id] });
    this.state.marks[id] = checkTone(tone);
    this.t.record(`visit ${fmt(this.node(id).value)}`);
  }

  private newId(): string {
    return `${this.state.name}:${this.counter++}`;
  }

  private node(id: string): TreeNode {
    const n = this.state.nodes[id];
    if (!n) throw new TraceError(`No node "${id}" in ${this.state.name}.`);
    return n;
  }

  /** @internal */
  clearTransient(): void {
    for (const item of this.transient.reverse()) {
      if (!this.state.nodes[item.id]) continue;
      if (item.prev === undefined) delete this.state.marks[item.id];
      else this.state.marks[item.id] = item.prev;
    }
    this.transient = [];
  }
}

export class TrackedVars {
  constructor(
    private readonly t: Tracer,
    private readonly state: VarsState,
  ) {}

  get(name: string): Value {
    return this.state.values[name] ?? null;
  }

  set(name: string, value: Value): void;
  set(values: Record<string, Value>): void;
  set(nameOrValues: string | Record<string, Value>, value?: Value): void {
    const updates =
      typeof nameOrValues === 'string' ? { [nameOrValues]: value ?? null } : nameOrValues;
    Object.assign(this.state.values, updates);
    this.state.changed = Object.keys(updates);
    this.t.record(
      Object.entries(updates)
        .map(([k, v]) => `${k} = ${fmt(v)}`)
        .join(', '),
    );
  }
}

export type TraceFunction = (t: Tracer) => void;

/** Run a trace function and return the recorded trace. */
export function runTrace(fn: TraceFunction, meta: TraceMeta = {}): Trace {
  const t = new Tracer();
  fn(t);
  const trace = t.result(meta);
  if (trace.frames.length === 0) throw new TraceError('The trace recorded no frames.');
  return trace;
}
